def engraving():
    # A family of tilted freestanding ellipses makes a single, twisted ribbon.
    loops = []
    for index in range(61):
        t = index / 60
        x = -83 + 166 * t
        y = 19 * math.sin(2 * math.pi * t - 0.5) - 9 * t
        rx = 74 + 13 * math.sin(math.pi * t)
        ry = 27 + 7 * math.sin(math.pi * t) ** 2
        angle = -62 + 127 * t
        loops.append(f'<ellipse cx="{x:.2f}" cy="{y:.2f}" rx="{rx:.2f}" ry="{ry:.2f}" '
                     f'transform="rotate({angle:.2f} {x:.2f} {y:.2f})"/>')
    return ('<g transform="translate(767 151) rotate(-16) scale(1.09)" '
            'fill="none" stroke="#F3C4AB" stroke-width="1.05">' + "".join(loops) + "</g>")


