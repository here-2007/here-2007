class PublicCalendar(HTMLParser):
    """Join GitHub's public heatmap cells to their English count tooltips by ID."""

    def __init__(self):
        super().__init__()
        self.cells = {}
        self.counts = {}
        self.tooltip = None
        self.words = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "td" and "data-date" in attrs:
            self.cells[attrs["id"]] = (attrs["data-date"], int(attrs["data-level"]))
        elif tag == "tool-tip":
            self.tooltip = attrs.get("for")
            self.words = []

    def handle_data(self, data):
        if self.tooltip:
            self.words.append(data)

    def handle_endtag(self, tag):
        if tag == "tool-tip" and self.tooltip:
            match = re.match(r"^(No|[\d,]+) contributions? on\b", "".join(self.words).strip())
            if match:
                raw = match[1]
                self.counts[self.tooltip] = 0 if raw == "No" else int(raw.replace(",", ""))
            self.tooltip = None

    def records(self):
        if self.cells.keys() - self.counts.keys():
            raise ValueError("A GitHub calendar cell is missing its count")
        return sorted(({"date": day, "count": self.counts[key], "level": level}
                       for key, (day, level) in self.cells.items()), key=lambda r: r["date"])


def read_days(snapshot):
    if snapshot["account"] != LOGIN:
        raise ValueError("The contribution snapshot belongs to a different account")
    days = [Day(date.fromisoformat(row["date"]), row["count"], row["level"])
            for row in snapshot["days"]]
    if not 364 <= len(days) <= 373:
        raise ValueError(f"Expected a year of daily contributions, received {len(days)} days")
    for index, day in enumerate(days):
        if (type(day.count) is not int or day.count < 0 or type(day.level) is not int
                or not 0 <= day.level < len(HEAT) or (day.count == 0) != (day.level == 0)):
            raise ValueError(f"Invalid count or colour level on {day.date}")
        if index and day.date != days[index - 1].date + timedelta(days=1):
            raise ValueError(f"Gap, duplicate or out-of-order date at {day.date}")
    return days


def write_changed(path, content):
    encoded = content.encode("utf-8")
    if path.exists() and path.read_bytes() == encoded:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with NamedTemporaryFile(dir=path.parent, delete=False) as tmp:
        tmp.write(encoded)
    Path(tmp.name).chmod(0o644)
    Path(tmp.name).replace(path)


def refresh():
    request = Request(CALENDAR_URL, headers={"Accept-Language": "en-US", "User-Agent": "here-2007-profile"})
    parser = PublicCalendar()
    with urlopen(request, timeout=35) as response:
        parser.feed(response.read().decode("utf-8"))
    parser.close()
    snapshot = {"account": LOGIN, "source": CALENDAR_URL, "days": parser.records()}
    days = read_days(snapshot)
    if abs((datetime.now(timezone.utc).date() - days[-1].date).days) > 1:
        raise ValueError(f"GitHub returned a stale calendar ending {days[-1].date}")
    write_changed(DATA, json.dumps(snapshot, indent=2) + "\n")
    print(f"Read {len(days)} public contribution days through {days[-1].date}")


def month_stats(days):
    """Use the latest date to break busiest-day ties and keep the current partial month.

    >>> first = date(2024, 2, 27)
    >>> days = [Day(first + timedelta(days=i), n, int(n > 0)) for i, n in enumerate((0, 2, 2, 0))]
    >>> months, streak, active, busiest = month_stats(days)
    >>> list(months.values()), streak, active, busiest.date.isoformat()
    ([4, 0], '2', 2, '2024-02-29')
    """
    end = days[-1].date
    start_year = end.year if end.month == 12 else end.year - 1
    start = date(start_year, end.month % 12 + 1, 1)
    visible = [day for day in days if day.date >= start]
    months = Counter()
    for day in visible:
        months[day.date.replace(day=1)] += day.count
    most = max(visible, key=lambda d: (d.count, d.date))
    # An unfinished day keeps yesterday's streak alive until the day closes.
    streak = 0
    candidates = days if days[-1].count else days[:-1]
    for day in reversed(candidates):
        if not day.count:
            break
        streak += 1
    streak_text = f"{streak}{'+' if streak == len(candidates) else ''}"
    return months, streak_text, sum(day.count > 0 for day in visible), most


def display_date(day):
    return f"{day.day} {calendar.month_abbr[day.month]} {day.year}"


def txt(x, y, value, size, *, face="sans", ink=INK, anchor="start", tracking=0):
    return (f'<text x="{x}" y="{y}" class="{face}" font-size="{size}" fill="{ink}" '
            f'text-anchor="{anchor}" letter-spacing="{tracking}">{escape(str(value))}</text>')


def path(d, ink, width=1.5, *, draw=False):
    trace = ' pathLength="1" stroke-dasharray="1 1"' if draw else ""
    return (f'<path d="{d}" fill="none" stroke="{ink}" stroke-width="{width}" '
            f'stroke-linecap="round" stroke-linejoin="round"{trace}>'
            f'{"<!--trace-->" if draw else ""}</path>')


