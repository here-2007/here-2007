def heatmap(days):
    start, end = days[0].date, days[-1].date
    sunday = start - timedelta(days=(start.weekday() + 1) % 7)
    n_weeks = (end - sunday).days // 7 + 1
    step = min(16.4, 846 / n_weeks)
    side = step - 2.8
    total = sum(day.count for day in days)
    span = f"{display_date(start)} – {display_date(end)}"
    items = [txt(36, 37, "@here-2007", 17, ink=CARMINE, tracking=0.8),
             txt(35, 84, "Contribution calendar", 43, face="display", tracking=-0.9),
             txt(924, 41, f"{total:,} contributions", 25, face="display", ink=WINE, anchor="end"),
             txt(924, 69, span, 17, ink=QUIET, anchor="end")]
    for row, name in ((1, "Mon"), (3, "Wed"), (5, "Fri")):
        items.append(txt(36, round(138 + row * step, 1), name, 16, ink=QUIET))
    weeks = [[] for _ in range(n_weeks)]
    label_first_month = calendar.monthrange(start.year, start.month)[1] - start.day >= 13
    for day in days:
        week, row = divmod((day.date - sunday).days, 7)
        x = 78 + week * step
        if day.date.day == 1 or (day.date == start and label_first_month):
            items.append(txt(round(x, 1), 116, calendar.month_abbr[day.date.month], 16, ink=QUIET))
        weeks[week].append(f'<rect x="{x:.2f}" y="{126 + row * step:.2f}" width="{side:.2f}" '
                           f'height="{side:.2f}" rx="2" fill="{HEAT[day.level]}"><title>'
                           f'{display_date(day.date)} · {day.count}</title></rect>')
    for i, cells in enumerate(weeks):
        items.append(f'<g class="week" style="--lag:{i * 0.009:.3f}s">{"".join(cells)}</g>')
    items.extend([path("M36 258h888", RULE, 1, draw=True), txt(36, 283, "Weeks start on Sunday", 17, ink=QUIET),
                  txt(765, 283, "Less", 16, ink=QUIET)])
    for i, colour in enumerate(HEAT):
        items.append(f'<rect x="{801 + 17 * i}" y="271" width="13" height="13" rx="2" fill="{colour}"/>')
    items.append(txt(924, 283, "More", 16, ink=QUIET, anchor="end"))
    return Card("calendar", 960, 301, PAPER, "Contribution calendar",
                f"GitHub contribution calendar for {LOGIN}, {span}. {total:,} contributions. Open the public activity.",
                "".join(items), 1.31 + len(PROJECTS) * 0.36, GITHUB + "#year-list-container")


def embedded_fonts(content, temp):
    characters = {face: set() for face in FONTS}
    for node in ElementTree.fromstring(f"<g>{content}</g>").iter("text"):
        characters[node.attrib["class"]].update(node.text or "")
    rules = []
    for face, chars in characters.items():
        if not chars:
            continue
        output = temp / f"{face}.woff"
        subprocess.run(["pyftsubset", str(FONTS[face]), "--text=" + "".join(sorted(chars)),
                        "--flavor=woff", "--no-hinting", "--no-recalc-timestamp", "--canonical-order",
                        "--name-IDs+=0,13,14", f"--output-file={output}"], check=True)
        data = base64.b64encode(output.read_bytes()).decode("ascii")
        rules.append(f"@font-face{{font-family:{face}Ink;src:url(data:font/woff;base64,{data}) format('woff')}}")
    return "\n".join(rules)


